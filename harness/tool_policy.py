"""実装役に許す道具の段階（B4-RUN v1.0 の裁定 2、docs/design/b4_ab_fairness_audit.md §6）。

A/B 実験の両条件（driver の条件 A と pipeline）が同じ文面を使う。

- タスクの最初の呼び出し：ビルド・テスト・探索をさせず、編集だけで終えさせる（最速・最安）
- 失敗を返したあとの呼び出し（再試行）：テストの実行と探索を許し、自分でデバッグさせる
"""

FIRST = ("ビルド・テスト・検証はこの外側のパイプラインが一元的に行い、失敗は次の指示で伝えます。"
         "この回はビルドもテストも実行せず、リポジトリの探索も最小限にして、対象ファイルを編集したら直ちに終えてください。")
RETRY = ("前回の実装は外側の検査で不合格になりました。この回に限り、dotnet test の実行やリポジトリの探索で"
         "原因を調べてかまいません。テストファイルは書き換えないでください。")


def text(retry):
    """再試行かどうかで、実装役への道具の指示を返す。"""
    return RETRY if retry else FIRST
