def tokenize(text, where):
    tokens, pos = [], 0
    while pos < len(text):
        if not text[pos:].strip():
            break
        m = TOKEN_RE.match(text, pos)
        if not m or m.end() == pos:
            raise PropertyError(f"{where}: 読めない字があります: {text[pos:pos + 10]!r}")
        num, name, op = m.groups()
        tokens.append(("int", int(num)) if num else ("name", name) if name else ("op", op))
        pos = m.end()
    return tokens


class _Parser:
    """再帰下降。優先順位は低い順に ||、&&、比較（== != < <= > >=）、+ -、単項（! -）。"""

    def __init__(self, tokens, where):
        self.t, self.i, self.where = tokens, 0, where

    def peek(self):
        return self.t[self.i] if self.i < len(self.t) else (None, None)

    def take(self, op=None):
        tok = self.peek()
        if op is not None and tok != ("op", op):
            raise PropertyError(f"{self.where}: {op!r} が要ります（{tok[1]!r} がありました）")
        self.i += 1
        return tok

    def parse(self):
        e = self.or_()
        if self.i != len(self.t):
            raise PropertyError(f"{self.where}: 式の後ろに余分なものがあります: {self.t[self.i][1]!r}")
        return e

    def binary(self, ops, sub):
        e = sub()
        while self.peek()[0] == "op" and self.peek()[1] in ops:
            op = self.take()[1]
            e = ("bin", op, e, sub())
        return e

    def or_(self):
        return self.binary(("||",), self.and_)

    def and_(self):
        return self.binary(("&&",), self.cmp)

    def cmp(self):
        e = self.add()
        if self.peek()[0] == "op" and self.peek()[1] in ("==", "!=", "<", "<=", ">", ">="):
            op = self.take()[1]
            e = ("bin", op, e, self.add())
        return e

    def add(self):
        return self.binary(("+", "-"), self.unary)

    def unary(self):
        if self.peek() in (("op", "!"), ("op", "-")):
            return ("un", self.take()[1], self.unary())
        return self.primary()

    def primary(self):
        kind, v = self.take()
        if kind == "int":
            return ("int", v)
        if (kind, v) == ("op", "("):
            e = self.or_()
            self.take(")")
            return e
        if kind == "name":
            if self.peek() == ("op", "("):
                self.take("(")
                args = []
                if self.peek() != ("op", ")"):
                    args.append(self.or_())
                    while self.peek() == ("op", ","):
                        self.take(",")
                        args.append(self.or_())
                self.take(")")
                return ("call", v, args)
            return ("name", v)
        raise PropertyError(f"{self.where}: 式が途中で終わっているか、{v!r} を置けない位置です")


def parse(text, where):
    return _Parser(tokenize(text, where), where).parse()


class _Typer:
    """構文木に型を付け、C# にする。型は int・bool・mino・mino?・null・列挙名。"""

    def __init__(self, contract, where):
        self.c, self.where = contract, where

    def err(self, msg):
        raise PropertyError(f"{self.where}: {msg}")

    def ctype(self, t):
        return {"int": "int", "bool": "bool", "mino": "ActiveMino", "mino?": "ActiveMino?"}.get(t, t)

    def of_member(self, t):
        return {"ActiveMino": "mino", "ActiveMino?": "mino?"}.get(t, t)

    def emit(self, e):
        """(C# の式, 型)。"""
        kind = e[0]
        if kind == "int":
            return str(e[1]), "int"
        if kind == "name":
            return self.name(e[1])
        if kind == "call":
            return self.call(e[1], e[2])
        if kind == "un":
            s, t = self.emit(e[2])
            want = "bool" if e[1] == "!" else "int"
            if t != want:
                self.err(f"{e[1]} は {want} にだけ使えます（{t}）")
            return f"({e[1]}{s})", t
        op, (ls, lt), (rs, rt) = e[1], self.emit(e[2]), self.emit(e[3])
        if op in ("&&", "||"):
            if lt != "bool" or rt != "bool":
                self.err(f"{op} の両辺は bool です（{lt}, {rt}）")
            return f"({ls} {op} {rs})", "bool"
        if op in ("+", "-", "<", "<=", ">", ">="):
            if lt != "int" or rt != "int":
                self.err(f"{op} の両辺は int です（{lt}, {rt}）")
            return f"({ls} {op} {rs})", "int" if op in ("+", "-") else "bool"
        return self.equality(op, ls, lt, rs, rt), "bool"

    def comparable(self, lt, rt):
        minos = {"mino", "mino?", "null"}
        if lt in minos and rt in minos:
            return not (lt == "null" and rt == "null") and not ("null" in (lt, rt) and "mino" in (lt, rt))
        return lt == rt

    def equality(self, op, ls, lt, rs, rt):
        if not self.comparable(lt, rt):
            self.err(f"{op} で {lt} と {rt} は比べられません")
        if lt in ("mino", "mino?", "null"):
            s = f"PropertyModel.Same({ls}, {rs})"
            return s if op == "==" else f"(!{s})"
        return f"({ls} {op} {rs})"

    def name(self, n):
        if n in ("true", "false"):
            return n, "bool"
        if n == "null":
            return "null", "null"
        parts = n.split(".")
        if len(parts) == 2 and parts[0] in self.c.enums and parts[1] in self.c.enums[parts[0]]:
            return f"global::{testgen.CORE_NAMESPACE}.{parts[0]}.{parts[1]}", parts[0]
        if len(parts) == 1:
            owners = [en for en, vs in self.c.enums.items() if n in vs]
            if len(owners) == 1:
                return f"global::{testgen.CORE_NAMESPACE}.{owners[0]}.{n}", owners[0]
            if owners:
                self.err(f"{n} は複数の列挙にあります。{owners[0]}.{n} のように書いてください")
        root = {"before": "b", "after": "a", "input": "i"}.get(parts[0])
        if root is None or len(parts) < 2:
            self.err(f"{n!r} は before・after・input のメンバー、列挙の値、true・false・null のどれでもありません")
        table = self.c.input if parts[0] == "input" else self.c.state
        if parts[1] not in table:
            self.err(f"{parts[0]} に {parts[1]} はありません（{sorted(table)}）")
        s, t = f"{root}.{parts[1]}", self.of_member(table[parts[1]])
        for p in parts[2:]:
            if t not in ("mino", "mino?"):
                self.err(f"{n}: {t} にメンバーはありません")
            if p not in self.c.mino:
                self.err(f"{n}: ActiveMino に {p} はありません（{sorted(self.c.mino)}）")
            s = f"PropertyModel.Req({s}).{p}" if t == "mino?" else f"{s}.{p}"
            t = self.of_member(self.c.mino[p])
        return s, t

    def call(self, fn, args):
        if fn not in FUNCS:
            self.err(f"関数 {fn} はありません（{sorted(FUNCS)}）")
        want, ret, build = FUNCS[fn]
        if len(args) != len(want):
            self.err(f"{fn} の引数は {len(want)} 個です")
        out = []
        for a, w in zip(args, want):
            s, t = self.emit(a)
            if w == "mino" and t == "mino?":
                s, t = f"PropertyModel.Req({s})", "mino"
            if t != w:
                self.err(f"{fn} の引数に {t} は渡せません（{w}）")
            out.append(s)
        return build(out), ret


def _strip(text):
    return re.sub(r"\s+", "", text)


def _label(text):
    """反例に出す、左辺の短い名前（after. / before. を落とす）。"""
    return re.sub(r"^(after|before)\.", "", _strip(text)).replace("\"", "'")


def _split_eq(text):
    """then の最上位が「左辺 == 右辺」なら (左辺, 右辺) の文字列。そうでなければ None。

    比較は結合しない（a == b == c は書けない）ので、最上位の == は括弧の外に 1 つだけある。
    """
    tree = parse(text, "then")
    if tree[0] != "bin" or tree[1] != "==":
        return None
    pos, depth = 0, 0
    while pos < len(text):
        m = TOKEN_RE.match(text, pos)
        if not m or m.end() == pos:
            break
        tok = m.group(3)
        depth += (tok == "(") - (tok == ")")
        if tok == "==" and depth == 0:
            return text[:m.start(3)].strip(), text[m.end():].strip()
        pos = m.end()
    return None


