DIRECTED_BASE, DIRECTED_MAX, DIRECTED_COUNT = 1_000_000_000, 20000, 3
PRE_STATE = ("Phase", "ActiveMino")   # 開始状態で実装を使わずに分かるもの（AtStart）
PRE_FUNCS = {"fits", "in_board", "moved", "rotated", "kick", "drop", "occupied_before"}


def _conjuncts(e):
    if e[0] == "bin" and e[1] == "&&":
        return _conjuncts(e[2]) + _conjuncts(e[3])
    return [e]


def _pre_ok(e):
    """開始状態だけで評価できる式か（before の Phase・ActiveMino、列挙・定数、after を使わない関数だけ）。"""
    kind = e[0]
    if kind == "int":
        return True
    if kind == "name":
        parts = e[1].split(".")
        if parts[0] == "before":
            return len(parts) >= 2 and parts[1] in PRE_STATE
        return parts[0] not in ("after", "input")
    if kind == "call":
        return e[1] in PRE_FUNCS and all(_pre_ok(a) for a in e[2])
    if kind == "un":
        return _pre_ok(e[2])
    return _pre_ok(e[2]) and _pre_ok(e[3])


def _phase_conflict(c, start_phase):
    """`before.Phase == X`（または `!=`）が、開始状態の局面（start.phase）では成り立たないか。

    開始状態はいつも start.phase なので、別の局面を求める前提（例：before.Phase == GameOver）は開始状態では決して成り立たない。
    その局面は系列の途中で起きる（v2r の T10）。これを開始状態の前提に入れると、探索が 0 本になり、実装に依らず
    PROPERTY_UNSATISFIABLE で落ちていた。
    """
    if start_phase is None or c[0] != "bin" or c[1] not in ("==", "!="):
        return False
    sides = [x for x in (c[2], c[3]) if x[0] == "name"]
    if len(sides) != 2 or "before.Phase" not in (sides[0][1], sides[1][1]):
        return False
    value = (sides[1] if sides[0][1] == "before.Phase" else sides[0])[1].split(".")[-1]
    return (value != start_phase) if c[1] == "==" else (value == start_phase)


def directed(p, start_phase=None):
    """前提の探索（v2.1e）の材料：(開始状態で評価する前提の式の列, 最初の手の入力 {名前: bool})。

    given を && で分け、`input.X`・`!input.X` を最初の手に、開始状態だけで評価できるものを前提にする。
    after を使うもの（固定ブロックが増えない、など）は、実装を動かさないと分からないので外す。
    start_phase を渡すと、開始状態の局面と食い違う局面の前提（_phase_conflict）も外す（系列の途中で起きる状態）。
    """
    pre, first = [], {}
    for c in _conjuncts(parse(str(p["given"]), f"{p['id']}.given")):
        lit = c[2] if c[0] == "un" and c[1] == "!" else c
        if lit[0] == "name" and lit[1].startswith("input.") and lit[1].count(".") == 1:
            name, val = lit[1].split(".")[1], c is lit
            if first.get(name, val) != val:
                raise PropertyError(f"{p['id']}.given: input.{name} が真と偽の両方を求めています")
            first[name] = val
        elif _pre_ok(c) and not _phase_conflict(c, start_phase):
            pre.append(c)
    return pre, first


SAMPLING_KEYS = {"start", "quiet", "rate", "count"}
MAX_DIRECTED_COUNT = 10


def sampling(p, rows):
    """前提を狙う抽出（Targeted State Sampling、v2.1f）の材料。(開始状態の制約の式の列, quiet, 千分率, 本数)。

    性質の宣言の任意のキー `sampling`：
    - `start`：開始状態の制約（開始状態だけで評価できる式。`_pre_ok`）。開始状態の分布をこの領域に絞る（拒否抽出）
    - `quiet`：開始から何手、入力を低頻度にするか。整数か `{"param": "PR-xx", "add": n}`（構造化仕様から引く）
    - `rate`：その区間で各キーを押す確率（0〜1）。0 なら無入力
    - `count`：足す系列の本数（1〜10。既定 3）
    固定のように「状態がある区間続いて初めて起きる」希薄な前提を、特定の操作列を書かずに、開始状態の領域と
    入力の分布で起こす。宣言が無ければ ([], 0, 0, 既定の本数)。
    """
    spec = p.get("sampling")
    if spec is None:
        return [], 0, 0, DIRECTED_COUNT
    where = f"{p['id']}.sampling"
    if not isinstance(spec, dict) or not spec.keys() <= SAMPLING_KEYS or "start" not in spec:
        raise PropertyError(f"{where}: キーは start（必須）・quiet・rate・count です")
    start = _conjuncts(parse(str(spec["start"]), f"{where}.start"))
    if not all(_pre_ok(c) for c in start):
        raise PropertyError(f"{where}.start: 開始状態だけで評価できる式にしてください（before の Phase・ActiveMino と、"
                            f"after を使わない関数）")
    q = spec.get("quiet", 0)
    if isinstance(q, dict):
        if set(q) - {"param", "add"} or q.get("param") not in rows:
            raise PropertyError(f"{where}.quiet: {{\"param\": \"PR-xx\", \"add\": 整数}} で構造化仕様にある ID を書いてください")
        base = unit_schema.resolve_param(rows[q["param"]][1], None)
        if not isinstance(base, int):
            raise PropertyError(f"{where}.quiet: {q['param']} の値が整数ではありません")
        q = base + int(q.get("add", 0))
    if isinstance(q, bool) or not isinstance(q, int) or not 0 <= q <= MAX_STEPS:
        raise PropertyError(f"{where}.quiet: 0 以上 {MAX_STEPS} 以下の整数にしてください")
    rate = spec.get("rate", 0)
    if isinstance(rate, bool) or not isinstance(rate, (int, float)) or not 0 <= rate <= 1:
        raise PropertyError(f"{where}.rate: 0 以上 1 以下にしてください")
    count = spec.get("count", DIRECTED_COUNT)
    if isinstance(count, bool) or not isinstance(count, int) or not 1 <= count <= MAX_DIRECTED_COUNT:
        raise PropertyError(f"{where}.count: 1 以上 {MAX_DIRECTED_COUNT} 以下の整数にしてください")
    return start, q, round(rate * 1000), count


def validate(decl, spec_text, gdd_text, interface):
    """問題の一覧（空なら合格）。"""
    if not isinstance(decl, dict):
        return ["宣言がオブジェクトではありません"]
    missing = sorted(TOP_KEYS - decl.keys())
    unknown = sorted(decl.keys() - TOP_KEYS - {k for k in decl if k.startswith("_")})
    if missing or unknown:
        return [f"キーが違います（不足: {missing}、不明: {unknown}）"]
    if decl["schema"] != SCHEMA:
        return [f"schema は {SCHEMA} です"]
    spec_ids, _, spec_problems = unit_schema.spec_index(spec_text, gdd_text)
    if spec_problems:
        return spec_problems
    if decl["gdd_sha256"] != hashlib.sha256(gdd_text.encode("utf-8")).hexdigest():
        return ["gdd_sha256 が今の GDD と一致しません。GDD が変わったので、性質の宣言を見直してから sha256 を更新してください"]
    problems = []
    try:
        contract = Contract(interface)
        ref = decl["reference"]
        if not isinstance(ref, dict) or set(ref) != REF_KEYS:
            raise PropertyError(f"reference のキーは {sorted(REF_KEYS)} です")
        rows = param_rows(spec_text)
        reference(ref, rows, contract)
    except PropertyError as e:
        return [str(e)]

    start = decl["start"]
    if not isinstance(start, dict) or not {"phase", "locked_max"} <= set(start) <= {"phase", "locked_max", "gap_rows"}:
        problems.append("start は {\"phase\", \"locked_max\"}（と任意の \"gap_rows\"）です")
    else:
        if start["phase"] not in contract.enums["GamePhase"]:
            problems.append(f"start.phase は GamePhase の値です: {start['phase']!r}")
        if isinstance(start["locked_max"], bool) or not isinstance(start["locked_max"], int) \
                or not 0 <= start["locked_max"] <= 100:
            problems.append("start.locked_max は 0 以上 100 以下の整数です")
        g = start.get("gap_rows", 0)
        if isinstance(g, bool) or not isinstance(g, int) or not 0 <= g <= 4:
            problems.append("start.gap_rows は 0 以上 4 以下の整数です")
    steps = decl["steps"]
    if isinstance(steps, bool) or not isinstance(steps, int) or not 1 <= steps <= MAX_STEPS:
        problems.append(f"steps は 1 以上 {MAX_STEPS} 以下の整数です")
    seeds = decl["seeds"]
    if not isinstance(seeds, dict) or set(seeds) != {"public", "hidden"} \
            or any(isinstance(v, bool) or not isinstance(v, int) for v in seeds.values()) \
            or not 1 <= seeds["public"] <= MAX_PUBLIC or not 0 <= seeds["hidden"] <= MAX_HIDDEN:
        problems.append(f"seeds は {{\"public\": 1〜{MAX_PUBLIC}, \"hidden\": 0〜{MAX_HIDDEN}}} です")

    props = decl["properties"]
    if not isinstance(props, list) or not props:
        return problems + ["properties は 1 つ以上の性質の列です"]
    ids, live = set(), {}
    for k, p in enumerate(props):
        where = f"properties[{k}]"
        if not isinstance(p, dict) or set(p) - {"_comment", "sampling"} != {"id", "task", "rule", "given", "then"}:
            problems.append(f"{where}: キーは id・task・rule・given・then（と任意の sampling）です")
            continue
        if not PROP_ID_RE.match(str(p["id"])) or p["id"] in ids:
            problems.append(f"{where}: id は P-T<n>-<2 桁以上> で重複しないこと: {p['id']!r}")
        ids.add(p["id"])
        if not TASK_RE.match(str(p["task"])):
            problems.append(f"{where}: task は T<n> です: {p['task']!r}")
        if not RULE_RE.match(str(p["rule"])) or p["rule"] not in spec_ids:
            problems.append(f"{where}: rule は構造化仕様にある ID（RL-xx・ST-xx・LP-xx）です: {p['rule']!r}")
        live.setdefault(p["task"], False)
        for key in ("given", "then"):
            try:
                _, t = _Typer(contract, f"{p['id']}.{key}").emit(parse(str(p[key]), f"{p['id']}.{key}"))
                if t != "bool":
                    problems.append(f"{p['id']}.{key}: 式は bool にしてください（{t}）")
            except PropertyError as e:
                problems.append(str(e))
        try:
            if _split_eq(str(p["then"])) is not None:
                live[p["task"]] = True
        except PropertyError:
            pass
        try:
            directed(p, (decl.get("start") or {}).get("phase") if isinstance(decl.get("start"), dict) else None)
            sampling(p, rows)
        except PropertyError as e:
            problems.append(str(e))
    for task, ok in sorted(live.items()):
        if not ok:
            problems.append(f"{task}: then が == の性質（活性の性質）が 1 つもありません（§4.2）")
    return problems


