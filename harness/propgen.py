class Contract:
    """契約の interface から、性質が参照できるものを取り出す。足りなければ PropertyError。"""

    def __init__(self, interface):
        self.types = {t["name"]: t for t in interface["types"]}
        need = [n for n in ("GamePhase", "MinoType", "Rotation", "ActiveMino", "TickInput", "Cell", "GameState")
                if n not in self.types]
        if need:
            raise PropertyError(f"契約に型がありません: {need}（docs/design/v2_contract_foundry.md §3.5）")
        self.enums = {n: t["values"] for n, t in self.types.items() if t["kind"] == "enum"}
        if len(self.enums["Rotation"]) != 4:
            raise PropertyError("Rotation は 4 値の列挙にしてください（向き 0・R・2・L の順）")
        gs = self.types["GameState"]["members"]
        if not any(m["kind"] == "method" and m["name"] == "IsOccupied" and m["type"] == "bool"
                   and [p["type"] for p in m.get("params", [])] == ["int", "int"] for m in gs):
            raise PropertyError("GameState に bool IsOccupied(int x, int y) がありません（§3.5）")
        self.restore = next((m for m in gs if m["kind"] == "ctor" and [p["type"] for p in m.get("params", [])]
                             == ["GamePhase", "ActiveMino?", "System.Collections.Generic.IReadOnlyList<Cell>"]), None)
        if self.restore is None:
            raise PropertyError("GameState に復元用コンストラクタ (GamePhase, ActiveMino?, IReadOnlyList<Cell>) がありません")
        # 状態として読めるもの：列挙・int・bool・ActiveMino・ActiveMino? の property
        self.state = {m["name"]: m["type"] for m in gs if m["kind"] == "property" and not m.get("static")
                      and self._scalar(m["type"])}
        self.mino = {m["name"]: m["type"] for m in self.types["ActiveMino"]["members"] if m["kind"] == "property"}
        self.input = {m["name"]: m["type"] for m in self.types["TickInput"]["members"] if m["kind"] == "property"}
        if sorted(self.input) != sorted(INPUT_ORDER):
            raise PropertyError(f"TickInput の property は {list(INPUT_ORDER)} にしてください")

    def _scalar(self, t):
        return t in ("int", "bool", "ActiveMino", "ActiveMino?") or t in self.enums


# ============================================================ 参照データ（構造化仕様 §5 から名前で引く）

def param_rows(spec_text):
    """{PR-xx: (名前, 値)}。"""
    problems = []
    _, tables = gdd_check.parse_doc(spec_text, gdd_check.SPEC_META,
                                    [(h, c) for h, _, c in gdd_check.SECTIONS], "spec.md", problems)
    rows = {}
    for head, rs in tables.items():
        if head.startswith("## 5."):
            rows.update({r["ID"]: (r["名前"], r["値"]) for r in rs})
    return rows


def _range(text, where):
    m = RANGE_RE.match(str(text))
    if not m or int(m.group(1)) > int(m.group(2)):
        raise PropertyError(f"reference.{where} は \"PR-a..PR-b\" の形にしてください: {text!r}")
    return [f"PR-{i:02d}" for i in range(int(m.group(1)), int(m.group(2)) + 1)]


def _coords(value, n, where):
    cs = [(int(x), int(y)) for x, y in gdd_check.COORD_RE.findall(value)]
    if n is not None and len(cs) != n:
        raise PropertyError(f"{where}: 座標が {n} 個ではありません: {value!r}")
    return cs


def reference(decl_ref, rows, contract):
    """{"width", "height", "shapes": {型: [[(x, y)]*4 （向きの順）]}, "kicks": {型: {(from, to): [(dx, dy)]}}}。"""
    def scalar(key):
        pid = decl_ref[key]
        if pid not in rows:
            raise PropertyError(f"reference.{key}: {pid} が構造化仕様にありません")
        v = unit_schema.resolve_param(rows[pid][1], None)
        if not isinstance(v, int) or v <= 0:
            raise PropertyError(f"reference.{key}: {pid} の値が正の整数ではありません: {rows[pid][1]!r}")
        return v

    types, rot_of = contract.enums["MinoType"], {lab: i for i, lab in enumerate(ROT_LABELS)}
    shapes = {t: [None] * 4 for t in types}
    for pid in _range(decl_ref["shapes"], "shapes"):
        name, value = rows.get(pid, (None, None))
        if name is None:
            raise PropertyError(f"reference.shapes: {pid} が構造化仕様にありません")
        if ORIGIN_RE.match(name):
            continue   # 回転原点は向きごとの形に織り込み済み
        m = SHAPE_RE.match(name)
        if not m or m.group(1) not in shapes or m.group(2) not in rot_of:
            raise PropertyError(f"reference.shapes: {pid} の名前を読めません: {name!r}")
        shapes[m.group(1)][rot_of[m.group(2)]] = _coords(value, 4, pid)
    missing = [f"{t} 向き {ROT_LABELS[r]}" for t in types for r in range(4) if shapes[t][r] is None]
    if missing:
        raise PropertyError(f"reference.shapes: 形がありません: {missing}")

    kicks = {t: {} for t in types}
    for pid in _range(decl_ref["kicks"], "kicks"):
        name, value = rows.get(pid, (None, None))
        if name is None:
            raise PropertyError(f"reference.kicks: {pid} が構造化仕様にありません")
        m, m_all = KICK_RE.match(name), KICK_ALL_RE.match(name)
        if m_all:
            pairs, owners = [(f, (f + d) % 4) for f in range(4) for d in (1, -1)], m_all.group(1).split("・")
        elif m and m.group(2) in rot_of and m.group(3) in rot_of:
            pairs, owners = [(rot_of[m.group(2)], rot_of[m.group(3)])], m.group(1).split("・")
        else:
            raise PropertyError(f"reference.kicks: {pid} の名前を読めません: {name!r}")
        for t in owners:
            if t not in kicks:
                raise PropertyError(f"reference.kicks: {pid} の型 {t} が MinoType にありません")
            for pair in pairs:
                kicks[t][pair] = _coords(value, None, pid)
    missing = [f"{t} {ROT_LABELS[f]} → {ROT_LABELS[(f + d) % 4]}" for t in types for f in range(4) for d in (1, -1)
               if (f, (f + d) % 4) not in kicks[t]]
    if missing:
        raise PropertyError(f"reference.kicks: 候補がありません: {missing[:5]}")
    return {"width": scalar("board_width"), "height": scalar("board_height"), "shapes": shapes, "kicks": kicks}


