def _check_method(p, contract, rows=None, start_phase=None):
    name = p["id"].replace("-", "_")
    given, _ = _Typer(contract, f"{p['id']}.given").emit(parse(p["given"], f"{p['id']}.given"))
    typer = _Typer(contract, f"{p['id']}.then")
    lines = [f"        public static int {name}(Snapshot b, global::{testgen.CORE_NAMESPACE}.TickInput i, Snapshot a,",
             "            out string expected, out string actual)", "        {",
             "            expected = null; actual = null;", "            bool g;",
             f"            try {{ g = {given}; }} catch (PropertyNull) {{ return 0; }}",
             "            if (!g) return 0;"]
    eq = _split_eq(p["then"])
    if eq is not None:
        (ls, _), (rs, _) = typer.emit(parse(eq[0], p["id"])), typer.emit(parse(eq[1], p["id"]))
        label = _label(eq[0])
        lines += ["            object l, r;",
                  f"            try {{ l = {ls}; }} catch (PropertyNull) {{ l = null; }}",
                  f"            try {{ r = {rs}; }} catch (PropertyNull) {{ r = null; }}",
                  "            if (PropertyModel.Same(l, r)) return 1;",
                  f"            expected = \"{label}:\" + PropertyRunner.Fmt(r);",
                  f"            actual = \"{label}:\" + PropertyRunner.Fmt(l);",
                  "            return 2;"]
    else:
        then, _ = typer.emit(parse(p["then"], p["id"]))
        label = _strip(p["then"]).replace("\"", "'")
        lines += ["            bool t;",
                  f"            try {{ t = {then}; }} catch (PropertyNull) {{ t = false; }}",
                  "            if (t) return 1;",
                  f"            expected = \"{label}:true\";",
                  f"            actual = \"{label}:false\";",
                  "            return 2;"]
    lines.append("        }")
    # 前提の探索（Directed）の材料：開始状態だけで評価する前提と、最初の手
    pre, first = directed(p, start_phase)
    # 抽出の宣言（sampling.start）があれば、開始状態の制約として前提に足す（v2.1f）
    pre = pre + sampling(p, rows or {})[0]
    pre_cs = " && ".join(_Typer(contract, f"{p['id']}.given").emit(c)[0] for c in pre) or "true"
    args = ", ".join("true" if first.get(n) else "false" for n in INPUT_ORDER)
    lines += ["", f"        public static bool Pre_{name}(Snapshot b) => {pre_cs};",
              f"        public static global::{testgen.CORE_NAMESPACE}.TickInput First_{name} =>",
              f"            new global::{testgen.CORE_NAMESPACE}.TickInput({args});"]
    return lines


def _sampling_args(p, rows):
    """Run に渡す抽出の引数（quiet・千分率・本数）。宣言が無ければ空（既定のまま）。"""
    if p.get("sampling") is None:
        return ""
    _, quiet, rate, count = sampling(p, rows or {})
    return f", quiet: {quiet}, ratePerMille: {rate}, count: {count}"


def _tests(task, props, decl, rows=None):
    ns = f"global::{NAMESPACE}"
    out = [HEADER, "#nullable disable", f"namespace {NAMESPACE}", "{",
           "    [global::NUnit.Framework.TestFixture]",
           f"    public sealed class Properties{task}Cases", "    {",
           f"        const int Steps = {decl['steps']};",
           f"        static readonly int[] PublicSeeds = PropertyRunner.Public({decl['seeds']['public']});", ""]
    for p in props:
        name = p["id"].replace("-", "_")
        for suffix, seeds in (("Public", "PublicSeeds"), ("Hidden", "PropertyRunner.Hidden()")):
            out += ["        [global::NUnit.Framework.Test]",
                    f"        [global::NUnit.Framework.Description(\"{p['rule']}\")]",
                    f"        public void {name}_{suffix}() =>",
                    f"            PropertyRunner.Run(\"{p['id']}\", \"{p['rule']}\", {seeds}, Steps, {ns}.Checks.{name},",
                    f"                {ns}.Checks.Pre_{name}, {ns}.Checks.First_{name}{_sampling_args(p, rows)});",
                    ""]
    out[-1:] = ["    }", "}", ""]
    return "\n".join(out)


def generate(decl, spec_text, gdd_text, interface, test_dir, tasks=None, report_hits=False):
    """{リポジトリからの相対パス: C#}。決定論。検査に落ちる宣言は PropertyError。

    report_hits：性質ごとに前提が成り立った回数（given）を標準出力に 1 行（PROPERTY_HITS）出す（v2r §8）。
    測定器は TRX の標準出力から読む（adapters/dotnet.property_hits）。

    tasks：テストのクラスを出すタスク（例 {"T1"}）。None なら全部。参照モデルと判定（Checks.cs）は常に全部出す。
    タスクを積み重ねるとき、まだ実装していないタスクの性質を置くと、それが落ちて受入の判定を汚す。
    """
    problems = validate(decl, spec_text, gdd_text, interface)
    if problems:
        raise PropertyError("性質の宣言が検査を通りません: " + "; ".join(problems[:5]))
    contract = Contract(interface)
    rows = param_rows(spec_text)
    ref = reference(decl["reference"], rows, contract)
    base = f"{test_dir}/{OUT_DIR}"
    files = {f"{base}/PropertyModel.cs": _model(ref, contract, decl["start"], report_hits)}
    checks = [HEADER, "#nullable disable", f"using ActiveMino = global::{testgen.CORE_NAMESPACE}.ActiveMino;", "",
              f"namespace {NAMESPACE}", "{", "    internal static class Checks", "    {"]
    for p in decl["properties"]:
        checks += _check_method(p, contract, rows, decl["start"]["phase"]) + [""]
    checks[-1:] = ["    }", "}", ""]
    files[f"{base}/Checks.cs"] = "\n".join(checks)
    wanted = tasks
    tasks = sorted({p["task"] for p in decl["properties"]}, key=lambda t: int(t[1:]))
    for task in tasks:
        if wanted is not None and task not in wanted:
            continue
        files[f"{base}/Properties{task}Cases.cs"] = _tests(task, [p for p in decl["properties"] if p["task"] == task],
                                                            decl, rows)
    return files


def lock(files):
    return {rel: hashlib.sha256(text.encode("utf-8")).hexdigest() for rel, text in sorted(files.items())}


def main(argv=None):
    ap = argparse.ArgumentParser(description="性質の宣言から、性質テスト・参照モデルを作る")
    ap.add_argument("--project", required=True)
    ap.add_argument("--decl", required=True, help="properties.json")
    ap.add_argument("--interface", required=True, help="契約の interface（単位定義か interface の JSON）")
    ap.add_argument("--out", required=True, help="書き出し先（リポジトリからの相対パスをそのまま下に作る）")
    args = ap.parse_args(argv)
    proj = project.load(args.project)
    cfg = project.config("unit_schema")
    read = unit_schema.git_reader(proj["repo_dir"], f"origin/{proj['base_branch']}", 120)
    iface = json.loads(Path(args.interface).read_text(encoding="utf-8"))
    iface = iface["interface"] if "interface" in iface else iface
    try:
        files = generate(json.loads(Path(args.decl).read_text(encoding="utf-8")),
                         read(cfg["spec_path"]), read(cfg["gdd_path"]), iface, proj["test_dir"])
    except (PropertyError, unit_schema.UnitSchemaError) as e:
        print(f"NG: {e}")
        return 1
    out = Path(args.out)
    for rel, text in files.items():
        p = out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(text.encode("utf-8"))
    (out / "property.lock.json").write_text(json.dumps(lock(files), ensure_ascii=False, indent=2) + "\n",
                                            encoding="utf-8", newline="\n")
    print(f"書き出し: {len(files)} ファイル（{out}）")
    return 0


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(exitcode.normalized(main))
