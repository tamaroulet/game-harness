"""実装役に渡すファイルの中身を、ハーネスがプロンプトに埋め込み、細い作業場所に置く。

- 埋め込み（docs/design/v2_1_improvement_plan.md §1.1 の 2）：実装役が自分でファイルを読む手番をなくす。埋め込むのは、
  書き換えてよいファイル（whitelist）、契約の生成物（contractgen が作った読み取り専用のファイル。参照データの
  GddReference を含む）、base の既存の型。総監督は中身を見ない（ハーネスが機械的に埋める）
- 並び（v2.1c §3 の 3）：変わらない前置き（契約・既存の型）を先に、変わるもの（書き換えてよいファイル）を後に置く。
  呼び出しをまたいで前置きの字面が同じになり、キャッシュに乗る
- 仕様書の文章は埋め込まない（v2.1c、2026-09-25 の裁定 1）。v2.1b は単位定義の prompt から正規表現で仕様 ID を拾い、
  構造化仕様の行を抜き出していたが、自然言語で実装役を導くのは v2 の原則に反し、範囲の表記（PR-52〜PR-68）で
  15 行が欠けた。参照データは契約（GddReference）に、規則は性質の宣言（単位定義の prompt）に一元化した
- 上限（MAX_CHARS）を超えたら ContextError。省いて「必要なら読んでください」と書くと、読みに行く手番を促す
"""
import re
from pathlib import Path

CONTRACT_MARKER = "// <auto-generated> contractgen"
MAX_CHARS = 60000


class ContextError(Exception):
    pass


def contract_files(root, impl_dir):
    """impl_dir の下の、contractgen の生成物（リポジトリからの相対パス）。先頭の行で見分ける。"""
    base = Path(root) / impl_dir
    out = []
    if not base.exists():
        return out
    for p in sorted(base.rglob("*")):
        if not p.is_file() or p.name.endswith(".meta"):
            continue
        try:
            head = p.read_text(encoding="utf-8", errors="replace").lstrip("﻿")[:60]
        except OSError:
            continue
        if head.startswith(CONTRACT_MARKER):
            out.append(p.relative_to(root).as_posix())
    return out


def type_files(root, unit, impl_dir):
    """unit の interface にある型の、base の既存のファイル（impl_dir/<型名><拡張子>）。拡張子は whitelist から取る。

    実装役が既存の型（ActiveMino など）を読みに行く手番をなくす（v2.1b §5 の 1）。
    """
    wl = unit.get("whitelist") or []
    suffix = Path(wl[0]).suffix if wl else ""
    out = []
    for t in (unit.get("interface") or {}).get("types", []):
        rel = f"{impl_dir}/{t['name']}{suffix}"
        if rel not in wl and (Path(root) / rel).exists():
            out.append(rel)
    return out


def readonly_files(root, unit, impl_dir):
    """読み取り専用で見せるもの：契約の生成物と base の既存の型（重複なし、順は決定論）。"""
    out = []
    for rel in contract_files(root, impl_dir) + type_files(root, unit, impl_dir):
        if rel not in out:
            out.append(rel)
    return out


def visible_files(root, unit, impl_dir):
    """実装役の作業場所に置くもの（= 埋め込むもの）。書き換えてよいファイルと、読み取り専用のもの。"""
    return list(unit.get("whitelist") or []) + readonly_files(root, unit, impl_dir)


def for_unit(root, unit, impl_dir):
    """実装役に渡す前提の全部：契約（参照データを含む）、base の既存の型、書き換えてよいファイル。"""
    return blocks(root, unit.get("whitelist") or [], readonly_files(root, unit, impl_dir))


def blocks(root, editable, readonly):
    """プロンプトに足す文章。readonly（契約。書き換え不可）を先に、editable（書き換えてよいファイル）を後に置く。"""
    # 作業場所の一覧を先に示す（v2.1d：v2-dry-05c の実装役は、一覧を知るために端末のコマンドを繰り返した）
    present = [rel for rel in list(readonly) + list(editable) if (Path(root) / rel).exists()]
    parts = ["## いまのファイルの中身（ハーネスが埋め込んだもの。作業場所にあるファイルはこれで全部です）",
             "作業場所のファイル一覧：\n" + "\n".join(f"- {rel}" for rel in present)]
    used = 0
    for title, rels in (("読み取り専用（契約。書き換えない）", readonly), ("書き換えてよいファイル", editable)):
        for rel in rels:
            p = Path(root) / rel
            if not p.exists():
                parts.append(f"### {rel}（{title}）\nまだありません。必要なら新しく作ってください。")
                continue
            text = p.read_text(encoding="utf-8", errors="replace").lstrip("﻿")
            used += len(text)
            if used > MAX_CHARS:
                raise ContextError(f"埋め込みが上限（{MAX_CHARS} 字）を超えます（{rel} まで {used} 字）")
            parts.append(f"### {rel}（{title}）\n```\n{text.rstrip()}\n```")
    return "\n\n".join(parts)


PARAM_RE = re.compile(r"PR-(\d{2,})(?:\s*(?:〜|～|\.\.|-)\s*PR-(\d{2,}))?")


def referenced_params(text):
    """文章が参照する PR の ID。範囲の表記（PR-52〜PR-68・PR-52..PR-68）は展開する。"""
    ids = set()
    for m in PARAM_RE.finditer(text or ""):
        lo = int(m.group(1))
        hi = int(m.group(2)) if m.group(2) else lo
        ids.update(f"PR-{i:02d}" for i in range(lo, max(lo, hi) + 1))
    return ids
