"""改善ループの PR の本文と、Argon の事後の評価の材料を、機械の記録の数だけで作る（v3 §7-9、L7）。外に何も送らない。

公開のリポジトリには、チェーン課題の中身（題・数値・直す所・試験の名）を書かない。提案の文は開発用のセットの生ログを読んで書かれていて、
中身が混ざりうるので、ここには入れない（手元の提案の記録を読む）。入れるのは、次の欄の数だけ：
版・ラン・直した数・壊した数・通ったステージ・新しい試験・既存テストの保持・トークン。held-out は合計だけで、ステージの名を書かない。
Argon の判定と判断点は、Argon が合計だけを材料に、公開の写しを読んで書いたものなので、本文に載せる。
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import surface  # noqa: E402

LOCAL_PATH = re.compile(r"[A-Za-z]:[\\/]|\$\{local\}|[\\/]\.local[\\/]")
SHA = re.compile(r"[0-9a-f]{7,40}")
TAG = re.compile(r"[A-Za-z0-9._-]+")
STAGE = re.compile(r"[A-Za-z0-9_-]+:[0-9]+")
GENERATED = "🤖 Generated by harness.cycle（改善ループの見回り）"
ARGON_ASK = ("1. 差分が最適化の面の中の、どの課題にも効く一般の手順か（特定の課題の式・変数名・試験の名・数値に依らないか）。\n"
             "2. 下の数が、v3 §7-7 の 3・4 の決まりと config/cycle.json の線に照らして、取り込みの基準を満たすか。\n"
             "3. 差分に副作用が無いか（実装役への指示とつまみのほかを変えていないか）。\n"
             "書き手の言い分をそのまま信じず、コードで確かめてほしい。チェーン課題の中身は文に書かないでほしい。")


class TemplateError(Exception):
    """数でない値か、形の違う名が欄に来た。本文を作らない（自由な文が公開に出る道を塞ぐ）。"""


def public_problems(name, text, words=(), loose=()):
    """公開に出す文 1 つ（PR の本文か集計のファイル）の当たりの文の列。中身は出さず、名と行だけ。
    words は隠しテストの名、loose は package の名（surface.leaks の決まり）。土台の名は公開の集計に入るので見ない。
    集計の reason の欄には、基盤の失敗の出力（ローカルのパスや名）が入りうる（Argon の事前の評価の指摘）。"""
    lines = list(enumerate(text.splitlines(), 1))
    hits = [f"ローカルのパス: {name}:{n}" for n, line in lines if LOCAL_PATH.search(line)]
    return hits + surface.leaks([(name, n, line) for n, line in lines], words, loose)


def count(value, name):
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        raise TemplateError(f"{name} が数ではありません: {value!r}")
    return value


def ratio(pair, name):
    if not isinstance(pair, (list, tuple)) or len(pair) != 2:
        raise TemplateError(f"{name} が [通った, 全部] ではありません: {pair!r}")
    return f"{count(pair[0], name)}/{count(pair[1], name)}"


def named(pattern, value, name):
    if not isinstance(value, str) or not pattern.fullmatch(value):
        raise TemplateError(f"{name} の形が違います: {value!r}")
    return value


def tokens(value, name="トークン"):
    return f"{count(value, name) / 10000:,.0f} 万"


def run_line(label, run):
    return (f"| {label} | {count(run['passed'], '通ったステージ')}/{count(run['stages'], 'ステージ')} | {ratio(run['new'], '新しい試験')} "
            f"| {ratio(run['kept'], '既存テストの保持')} | {tokens(run['tokens'])} |")


def table(rows):
    return ["| | 通ったステージ | 新しい試験 | 既存テストの保持 | トークン |", "|:--|:--|:--|:--|:--|", *rows]


def numbers(rec):
    """本文と Argon の材料に共通の、数の節（行の列）。"""
    pair = rec["pair"]
    stages = "・".join(named(STAGE, s, "ステージ") for s in pair["stages"])
    return [f"- 周期：{named(TAG, rec['id'], 'id')}", f"- 測った版：旧版 {named(SHA, rec['rev'], '旧版')}、新版 {named(SHA, rec['head'], '新版')}", "",
            "**狙いの直り（v3 §7-7 の 3）**", "",
            f"- 対象のステージ：{stages}",
            f"- 直した {count(pair['fixed'], '直した')}・壊した {count(pair['broke'], '壊した')}・変わらない {count(pair['same'], '変わらない')}"
            f"・数えなかった {count(pair['skipped'], '数えなかった')}", "",
            "**回帰の守り（v3 §7-7 の 4）**", "",
            *table([run_line("開発用：新版", rec["dev"]), *(run_line(f"開発用：基準 {i}", b) for i, b in enumerate(rec["dev_base"], 1)),
                    run_line("held-out：新版", rec["held"]), *(run_line(f"held-out：基準 {i}", b) for i, b in enumerate(rec["held_base"], 1))])]


def argon_focus(rec):
    """argon_eval post の --with に渡す材料。"""
    return "\n".join(["# 照らしてほしいこと：改善ループの 1 周の取り込み", "", "## 頼み", "", ARGON_ASK, "", "## 機械の記録", "", *numbers(rec), ""])


def surface_body(rec, argon=None):
    """面の差分の PR の本文。argon は (判定, 判断点) か、まだなら None。"""
    verdict = "（Argon の事後の評価はこれから）" if argon is None else f"判定 {named(re.compile('LOW|MEDIUM|HIGH'), argon[0], '判定')}：{' '.join(str(argon[1]).split())}"
    return "\n".join(["## 何を変えるか", "", "改善ループが提案し、機械がコミットにした最適化の面の差分（実装役への指示か、面の設定のつまみ）。"
                      "提案の文はチェーン課題の中身が混ざりうるので、ここに書かない。", "",
                      "## 機械の記録", "", *numbers(rec), "", "## Argon の事後の評価", "", verdict, "",
                      "マージは操縦士がする（v3 §7-9）。", "", GENERATED, ""])


def records_body(rec, outcome):
    """集計の記録の PR の本文。outcome は決まった語（取り込みの候補 | 取り込まない：<段階>）。"""
    return "\n".join(["## 何を変えるか", "", f"改善ループの周期 {named(TAG, rec['id'], 'id')} の、公開の集計の数だけを足す（試験の名は入らない。held-out は合計だけ）。", "",
                      f"- 結果：{outcome}", f"- 周期の版：{named(SHA, rec['rev'], '版')}", "", GENERATED, ""])
