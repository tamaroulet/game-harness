"""版の正本（config/toolchain.json。ADR-004 の束 F、W-126）と、そこから作るもの。

    python -m harness.toolchain lock [--check]     requirements.lock を台帳から書く（--check は違えば終了コード 1）
    python -m harness.toolchain warmup <dir>       CI の NuGet の warm-up の csproj を <dir> に書く

**なぜ要るか**: 版が旧 config/environment.json・CI・invgen.json・requirements.lock・witness の自己試験に別々に書かれ、
1 か所だけ変わって食い違っても気づけなかった（claude の固定は 2.1.258 のまま、実物は 2.1.309。mujoco は lock に無く、
CI が直に入れていた）。版はこの台帳にだけ書き、ほかのものはここから作るか、ここを読む。実物との照合は harness/envcheck.py。
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import exitcode  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
TOOLCHAIN = ROOT / "config" / "toolchain.json"
LOCK = ROOT / "requirements.lock"
# pip がコードページ 932 の Windows でも読めるように、ASCII だけで書く
LOCK_HEADER = "# Generated by `python -m harness.toolchain lock` from config/toolchain.json. Do not edit.\n"

CSPROJ = """<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>{tf}</TargetFramework>
  </PropertyGroup>
  <ItemGroup>
{packages}
  </ItemGroup>
</Project>
"""


def load(path=TOOLCHAIN):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def target_framework(tc=None):
    return (tc or load())["csproj"]["target_framework"]


def csproj_packages(tc=None):
    """ハーネスが作る csproj の {パッケージ: 版}。"""
    return dict((tc or load())["csproj"]["packages"])


def package_references(packages=None, indent="    "):
    """csproj の PackageReference の行（改行でつなぐ）。"""
    packages = csproj_packages() if packages is None else packages
    return "\n".join(f'{indent}<PackageReference Include="{k}" Version="{v}" />' for k, v in packages.items())


def lock_text(tc=None):
    pkgs = (tc or load())["python_packages"]
    return LOCK_HEADER + "".join(f"{k}=={v}\n" for k, v in sorted(pkgs.items()))


def warmup_csproj(tc=None):
    tc = tc or load()
    return CSPROJ.format(tf=target_framework(tc), packages=package_references(csproj_packages(tc)))


def main(argv=None):
    ap = argparse.ArgumentParser(description="版の正本から requirements.lock と csproj を作る")
    sub = ap.add_subparsers(dest="action", required=True)
    lk = sub.add_parser("lock")
    lk.add_argument("--check", action="store_true")
    wu = sub.add_parser("warmup")
    wu.add_argument("dir")
    args = ap.parse_args(argv)
    if args.action == "lock":
        want = lock_text()
        have = LOCK.read_text(encoding="utf-8") if LOCK.exists() else ""
        if args.check:
            if have != want:
                print("NG: requirements.lock が config/toolchain.json と違います（python -m harness.toolchain lock で書き直す）")
                return 1
            print("一致")
            return 0
        LOCK.write_bytes(want.encode("utf-8"))
        print(f"書きました: {LOCK.name}")
        return 0
    d = Path(args.dir)
    d.mkdir(parents=True, exist_ok=True)
    (d / "Warmup.csproj").write_bytes(warmup_csproj().encode("utf-8"))
    print(d / "Warmup.csproj")
    return 0


if __name__ == "__main__":
    sys.exit(exitcode.normalized(main))
